#!/usr/bin/env python3
"""Per-cell summary of an ablation campaign: solve rate, tokens, active wall, phases, η, tool use.

    pixi run python scripts/ablation-report.py            # prints a table; --json for machine output
"""
from __future__ import annotations

import json
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from quod import trace  # noqa: E402
from quod.models import Rigor  # noqa: E402
from quod import provenance
from quod.state import StateStore  # noqa: E402


def main() -> None:
    cells: dict[str, list[dict]] = {}
    with StateStore() as s:
        for b in s.branches():
            cell = next((t.split(":", 1)[1] for t in b.tags if t.startswith("ablation:")), None)
            if not cell or b.status == "abandoned":
                continue
            a = trace.analyze(s, b.id)
            calls = s.tool_calls(b.id)
            a["_python_calls"] = sum(1 for c in calls if c["kind"] == "compute.python")
            a["_engine_calls"] = sum(1 for c in calls if c["kind"] in ("engine.attack", "engine.check", "lean.hammer", "propose"))
            a["_critic_calls"] = a["critic"]["calls"]
            cells.setdefault(cell, []).append(a)

    def mean(xs):
        xs = [x for x in xs if x is not None]
        return st.mean(xs) if xs else None

    rows = []
    for cell, runs in sorted(cells.items()):
        solved = [r for r in runs if r["target"]["rigor"] == Rigor.FORMALLY_PROVED]
        rows.append({
            "cell": cell, "runs": len(runs), "solved": len(solved), "solve_rate": len(solved) / len(runs),
            "mean_Mtok": mean([r["tokens"]["input"] / 1e6 for r in runs]),
            "mean_wall_min": mean([r["wall_s"] / 60 for r in runs if r["wall_s"]]),
            "mean_epochs": mean([r["epochs"] for r in runs]),
            "mean_eta_per_Mtok": mean([r["eta_per_Mtok"] for r in runs]),
            "mean_eta_per_h": mean([r["eta_per_hour"] for r in runs]),
            "mean_explore_min": mean([r["phases"]["exploration_s"] / 60 for r in runs if r["phases"]["exploration_s"] is not None]),
            "mean_verify_min": mean([r["phases"]["verification_s"] / 60 for r in runs if r["phases"]["verification_s"] is not None]),
            "mean_lean_fail": mean([r["lean_checks"]["failed"] for r in runs]),
            "python_calls": sum(r["_python_calls"] for r in runs), "engine_calls": sum(r["_engine_calls"] for r in runs),
            "critic_calls": sum(r["_critic_calls"] for r in runs), "failed_strategies": sum(r["failed_strategies"] for r in runs),
        })
    if "--json" in sys.argv:
        print(json.dumps(rows, indent=2, default=str))
        return
    f = lambda x, w=6, d=1: ("-" if x is None else f"{x:{w}.{d}f}")  # noqa: E731
    print(f"{'cell':12s} {'n':>3s} {'solved':>6s} {'Mtok':>6s} {'wall':>6s} {'epochs':>6s} {'η/Mtok':>7s} {'η/h':>6s} {'explor':>6s} {'verify':>6s} {'leanF':>5s} {'py':>4s} {'eng':>4s} {'crit':>4s} {'fails':>5s}")
    for r in rows:
        print(f"{r['cell']:12s} {r['runs']:3d} {r['solve_rate']:6.0%} {f(r['mean_Mtok'],6,2)} {f(r['mean_wall_min'])} {f(r['mean_epochs'])} "
              f"{f(r['mean_eta_per_Mtok'],7)} {f(r['mean_eta_per_h'])} {f(r['mean_explore_min'])} {f(r['mean_verify_min'])} "
              f"{f(r['mean_lean_fail'],5)} {r['python_calls']:4d} {r['engine_calls']:4d} {r['critic_calls']:4d} {r['failed_strategies']:5d}")


if __name__ == "__main__" and "--md" not in sys.argv:
    main()


def write_markdown(path: str = "local/reports/ABLATION.md") -> None:
    """Reproducible write-up: per-cell table, per-problem grid, paired comparisons against `full`."""
    import re
    from collections import defaultdict
    from datetime import date

    from quod.paths import harness_root

    rows_json = json.loads(json.dumps(_collect(), default=str))
    grid: dict[str, dict[str, dict[str, tuple]]] = defaultdict(lambda: defaultdict(dict))
    with StateStore() as s:
        for b in s.branches():
            m = re.match(r"abl-(full|no-engines|no-strategy|respawn)-(\d{4}-[ab]\d)-r(\d)", b.id)
            if not m:
                continue
            cell, prob, rep = m.groups()
            t = s.get_claim(b.id + "-target")
            grid[prob][cell][rep] = (sum(e.tokens_in for e in s.epochs(b.id)) / 1e6, bool(t and t.rigor == Rigor.FORMALLY_PROVED),
                                     len(s.epochs(b.id)))
    cells = ["full", "no-engines", "no-strategy", "respawn"]
    L = [provenance.header_markdown("Ablation"),
         "Generated by `scripts/ablation-report.py` from harness state: one measured epoch per run (respawn cell: "
         "several short epochs), mid-difficulty problems, repetitions per cell as configured.", "",
         "| cell | n | solved | mean Mtok | mean wall (min) | η/Mtok | η/h | explore (min) | verify (min) | Lean fails | engine calls | critic calls |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows_json:
        L.append(f"| {r['cell']} | {r['runs']} | {r['solve_rate']:.0%} | {r['mean_Mtok']:.2f} | {r['mean_wall_min']:.1f} | {r['mean_eta_per_Mtok']:.1f} | "
                 f"{r['mean_eta_per_h']:.0f} | {r['mean_explore_min']:.1f} | {r['mean_verify_min']:.1f} | {r['mean_lean_fail']:.1f} | {r['engine_calls']} | {r['critic_calls']} |")
    L += ["", "## Per problem (input Mtok, rep 1 / rep 2; `*` = target not proved, `eN` = epochs used)", "",
          "| problem | " + " | ".join(cells) + " |", "|---|" + "---|" * len(cells)]
    for prob in sorted(grid):
        cellstr = []
        for c in cells:
            v = grid[prob].get(c, {})
            cellstr.append(" / ".join(f"{v[r][0]:.2f}{'' if v[r][1] else '*'}{'e' + str(v[r][2]) if v[r][2] > 1 else ''}" for r in sorted(v)))
        L.append(f"| {prob} | " + " | ".join(cellstr) + " |")
    # paired sign test vs full
    L += ["", "## Paired comparison against `full` (same problem, same rep)", "", "| cell | cheaper than full | median saving |", "|---|---|---|"]
    for c in cells[1:]:
        diffs = []
        for prob in grid:
            for rep in grid[prob].get("full", {}):
                if rep in grid[prob].get(c, {}):
                    f_, o_ = grid[prob]["full"][rep][0], grid[prob][c][rep][0]
                    diffs.append((f_ - o_) / f_ if f_ else 0)
        if diffs:
            diffs.sort()
            L.append(f"| {c} | {sum(d > 0 for d in diffs)} / {len(diffs)} | {diffs[len(diffs)//2]:+.0%} |")
    out = harness_root() / path
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")


def _collect():
    import io, contextlib
    buf = io.StringIO()
    argv = sys.argv[:]
    sys.argv = [argv[0], "--json"]
    try:
        with contextlib.redirect_stdout(buf):
            main()
    finally:
        sys.argv = argv
    return json.loads(buf.getvalue())


if __name__ == "__main__" and "--md" in sys.argv:
    write_markdown()
