#!/usr/bin/env python3
"""Write local/reports/BENCHMARKS.md from harness state: per-problem outcomes with measured cost, and — for
PutnamBench problems — which publicly listed leaderboard systems also solved each one.

    pixi run python scripts/bench-report.py            # writes local/reports/BENCHMARKS.md in the harness root
"""
from __future__ import annotations

import json
import re
import sys
from datetime import date, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from quod import provenance
from quod.models import Rigor  # noqa: E402
from quod.paths import harness_root  # noqa: E402
from quod.state import StateStore  # noqa: E402

ROOT = harness_root()
LB = ROOT / "bench" / "reference" / "putnambench-leaderboard.json"


def putnam_key(branch_id: str) -> str | None:
    m = re.search(r"(\d{4})-([ab]\d)", branch_id)
    return f"{m.group(1)} {m.group(2).upper()}" if m else None


def leaderboard() -> tuple[dict[str, list[tuple[str, str]]], int]:
    """problem -> [(system, budget)] for entries that publish per-problem lists; plus count of listing entries."""
    if not LB.exists():
        return {}, 0
    data = json.loads(LB.read_text())
    per: dict[str, list[tuple[str, str]]] = {}
    listing = 0
    for name, v in data.items():
        ns = v.get("num-solved") or {}
        if not any(k.startswith("lean") for k in ns):
            continue
        ids = set(re.findall(r"(\d{4})\s*([AB]\d)", v.get("note") or ""))
        if not ids:
            continue
        listing += 1
        for y, p in ids:
            per.setdefault(f"{y} {p}", []).append((name.strip(), str(v.get("condensed-compute-budget", ""))))
    return per, listing


def main() -> None:
    per, n_listing = leaderboard()
    rows = []
    with StateStore() as s:
        for b in s.branches():
            if "source:putnam" not in b.tags or b.status == "abandoned":
                continue
            claims = s.claims(b.id)
            target = next((c for c in claims if "target" in c.tags), None)
            eps = s.epochs(b.id)
            tin = sum(e.tokens_in for e in eps)
            tout = sum(e.tokens_out for e in eps)
            fails = len(s.failed_strategies(b.id))
            wall = 0.0
            for e in eps:
                if e.started_at and e.ended_at:
                    wall += (datetime.fromisoformat(e.ended_at) - datetime.fromisoformat(e.started_at)).total_seconds()
            crit = [a for a in s.attacks(branch_id=b.id) if a.kind == "llm_critique"]
            proof_lines = None
            if target and target.rigor == Rigor.FORMALLY_PROVED and target.formal and target.formal.lean:
                proof_lines = target.formal.lean.count("\n") + 1
            rows.append({
                "branch": b.id, "problem": putnam_key(b.id), "status": b.status,
                "target": target.rigor if target else "-", "epochs": len(eps),
                "tokens_in": tin, "tokens_out": tout, "failed_strategies": fails, "wall_s": wall,
                "critic": f"{sum(a.outcome in ('refuted','weakened') for a in crit)}/{len(crit)}" if crit else "-",
                "proof_lines": proof_lines,
            })
    rows.sort(key=lambda r: r["problem"] or "")
    solved = sum(r["target"] == Rigor.FORMALLY_PROVED for r in rows)
    lines = [
        provenance.header_markdown("Benchmarks", extra="Rows were measured as each run happened, so a file with "
                                  "rows older than this header mixes instruments; regenerate to compare."),
        "Generated by `scripts/bench-report.py` from harness state: one headless epoch per problem unless noted, "
        "reference answers stripped on import, token usage measured from the Claude CLI envelope (input includes "
        "prompt-cache reads).",
        "", "## PutnamBench (Lean 4)", "",
        f"**{solved} / {len(rows)} targets kernel-proved**, blind (reference answers stripped on import), measured "
        "token usage from the Claude CLI envelope (input includes prompt-cache reads).", "",
        "| problem | target | epochs | wall | tokens in / out | failed strategies | critic hits | proof lines |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['problem']} | `{r['target']}` | {r['epochs']} | {int(r['wall_s']//60)}m{int(r['wall_s']%60):02d}s | {r['tokens_in']/1e6:.2f}M / {r['tokens_out']/1e3:.0f}k | "
                     f"{r['failed_strategies']} | {r['critic']} | {r['proof_lines'] or '-'} |")
    if per:
        lines += ["", "### Per-problem comparison with publicly listed PutnamBench results", "",
                  f"{n_listing} leaderboard entries publish the exact problems they solved (snapshot in "
                  "`bench/reference/`). This is not a like-for-like score: those systems ran the whole 672-problem set "
                  "under pass@N or dollar budgets; Quod ran a hand-picked subset, once each. The column says how many of "
                  "those listing systems also solved the problem, and the smallest published budget among them.", "",
                  "| problem | Quod | listed systems that solved it | e.g. (budget) |", "|---|---|---|---|"]
        for r in rows:
            hits = per.get(r["problem"] or "", [])
            ex = "; ".join(f"{n} ({b})" for n, b in hits[:2]) if hits else "—"
            q = "proved" if r["target"] == Rigor.FORMALLY_PROVED else str(r["target"])
            lines.append(f"| {r['problem']} | {q} | {len(hits)} / {n_listing} | {ex} |")
    tot_in = sum(r["tokens_in"] for r in rows); tot_out = sum(r["tokens_out"] for r in rows)
    tot_wall = sum(r["wall_s"] for r in rows)
    lines += ["", f"Totals: {tot_in/1e6:.1f}M input tokens ({tot_out/1e3:.0f}k output), {int(tot_wall//60)} min of agent wall time, "
              f"{tot_in/len(rows)/1e6:.2f}M input tokens per problem." if rows else "", "",
              "Wall time is the agent's epoch (ORIENT to CHECKPOINT); Lean cache/build setup is excluded. Input tokens count every "
              "turn's context re-read (mostly prompt-cache hits), which is the honest number for usage limits.", "",
              "## Generated statements (recall-proof)", "",
              "See `quod bench score-gen`. Seed 11: 10/10 correct, 0 false promotions, 730k tokens (13.7 correct per Mtok).", ""]
    out = ROOT / "local" / "reports" / "BENCHMARKS.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out}: {solved}/{len(rows)} Putnam targets proved")


if __name__ == "__main__":
    main()
